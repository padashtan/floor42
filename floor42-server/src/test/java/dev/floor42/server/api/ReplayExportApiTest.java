package dev.floor42.server.api;

import static dev.floor42.server.api.LiveTestSupport.await;
import static io.restassured.RestAssured.given;
import static org.assertj.core.api.Assertions.assertThat;
import static org.hamcrest.Matchers.equalTo;
import static org.hamcrest.Matchers.greaterThan;

import dev.floor42.domain.MissionId;
import dev.floor42.domain.TicketStatus;
import dev.floor42.server.app.OfficeService;
import io.quarkus.test.junit.QuarkusTest;
import io.restassured.response.ExtractableResponse;
import io.restassured.response.Response;
import jakarta.inject.Inject;
import java.nio.file.Path;
import java.time.Duration;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.eclipse.microprofile.config.inject.ConfigProperty;
import org.junit.jupiter.api.Test;

/**
 * A mission played by the fake Claude Code whose tool outputs hold secrets and local paths, exported as a replay: the
 * file holds the events with their origin and the provenance header, and none of the secrets, paths or the token.
 */
@QuarkusTest
class ReplayExportApiTest extends ApiTestBase {

    @Inject
    OfficeService office;

    @ConfigProperty(name = "floor42.data-dir")
    Path dataDir;

    @Test
    void theExportedFileHoldsNoSecretNoLocalPathAndNoToken() throws Exception {
        Path repo = LiveMissionTest.gitRepository();
        // The director's token is never put in the journal here (ADR-0034 forbids it at rest): masking a token that
        // reached a text is proven by ReplaySanitizerTest; this test proves it is absent from the file.
        String objective = "Describe " + repo + " [fake:leak] with key sk-ant-api03-abcdefghijklmnop";
        String id = api().body(Map.of("title", "Leaky", "objective", objective, "repository", repo.toString()))
                .post("/api/missions")
                .then()
                .statusCode(201)
                .extract()
                .path("id");
        MissionId m = new MissionId(id);
        api().body("{\"noCap\":true}")
                .post("/api/missions/" + id + "/approve")
                .then()
                .statusCode(200);
        await(
                "the reviewed delivery",
                Duration.ofSeconds(40),
                () -> office.query(c -> c.tickets().of(m).getFirst().status()) == TicketStatus.DONE);

        ExtractableResponse<Response> preview = api().get("/api/missions/" + id + "/replay-export/preview")
                .then()
                .statusCode(200)
                .body("mission", equalTo(id))
                .body("origin", equalTo("REAL"))
                .body("events", greaterThan(5))
                .body("simulated", equalTo(0))
                .body("costs", greaterThan(0))
                .extract();
        String digest = preview.path("digest");
        List<String> kinds = preview.path("masked.kind");
        assertThat(kinds).contains("SECRET", "PATH", "OUTPUT_CLIPPED");

        // The file is only for the content previewed and confirmed.
        api().body(Map.of())
                .post("/api/missions/" + id + "/replay-export")
                .then()
                .statusCode(400);
        api().body(Map.of("digest", "0".repeat(64)))
                .post("/api/missions/" + id + "/replay-export")
                .then()
                .statusCode(409)
                .body("code", equalTo("REPLAY_CHANGED"));
        given().contentType("application/json")
                .body(Map.of("digest", digest))
                .post("/api/missions/" + id + "/replay-export")
                .then()
                .statusCode(401);

        Response file = api().body(Map.of("digest", digest, "language", "fr", "labels", Map.of("real", "RÉEL")))
                .post("/api/missions/" + id + "/replay-export");
        assertThat(file.statusCode()).isEqualTo(200);
        assertThat(file.contentType()).startsWith("text/html");
        assertThat(file.header("Content-Disposition")).contains("floor42-replay-" + id + ".html");
        String html = file.asString();

        assertThat(html)
                .startsWith("<!DOCTYPE html>")
                .contains(
                        "Generated by Floor42 version",
                        "mission " + id,
                        "exported at",
                        "events as recorded; nothing added")
                .contains("\"origin\":\"REAL\"", "\"type\":\"ActionExecuted\"", "\"basis\":\"estimated\"")
                .contains("default-src 'none'", "RÉEL", "[masked]", "[clipped]", "\\u003cpath\\u003e")
                .contains("\\u003crepository\\u003e");
        List<String> forbidden = new ArrayList<>(List.of(
                token.value(),
                "sk-ant-api03-abcdefghijklmnop",
                "ghp_abcdefghijklmnopqrstuvwxyz0123",
                "AKIAABCDEFGHIJKLMNOP",
                "abcdefghijklmnop.qrstuvwxyz",
                "hunter2hunter2",
                "C:\\Users\\director",
                "C:\\\\Users\\\\director",
                "/home/director",
                "/Users/director",
                "fileserver"));
        for (String folder : List.of(
                repo.toString(), dataDir.toAbsolutePath().normalize().toString(), System.getProperty("user.home"))) {
            forbidden.add(folder);
            forbidden.add(folder.replace("\\", "\\\\"));
            forbidden.add(folder.replace('\\', '/'));
        }
        for (String f : forbidden)
            assertThat(html).as("the file must not hold %s", f).doesNotContain(f);
        // Outputs are clipped: the long text does not come whole.
        int lorem = html.split("lorem ipsum", -1).length - 1;
        assertThat(lorem).isPositive().isLessThan(120);
    }

    @Test
    void anUnknownMissionHasNoReplay() {
        api().get("/api/missions/M-999/replay-export/preview").then().statusCode(404);
    }
}
